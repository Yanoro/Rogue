#!/usr/bin/env python3
"""Identify and grade generated sprites with a local moondream, using constrained output.

Scratch tooling; not part of the game build.

Why constrained output, and why the first two attempts were wrong
-----------------------------------------------------------------
The first version of this tool asked free-form questions ("What is this object?",
"Rate the quality: poor, fair, good, or excellent.") and read back whatever prose
came out. That produced three failure modes, all of them artifacts of the method
rather than judgements about the image:

  * a question asking for a 1-10 number returned a paragraph of description and no
    number at all (0 of 8 images);
  * asking for "bad, ok, or good" returned an empty string on half the images;
  * worst, some replies degenerated into out-of-distribution junk --
    "!!!IMPORTANT!!!", "!!!IMAGE NOT GENERATED BY LANGUAGE!!!",
    "!!!IMAGE NOT GENERATED BY PIXEL ART!!!" -- which are not judgements and must
    not be reported as though they were.

moondream supports **structured output through Ollama's `format` parameter**
(either `format: "json"` or a full JSON schema, constrained by a grammar at
sampling time). With a schema the same questions produce clean, stable, typed
answers, and repeated runs agree exactly. This tool therefore uses a schema and
nothing else.

The generalisable lesson: before judging a model's answers, check what output
constraints it offers. Free-form prompting of a small VQA model measures the
prompt, not the model.

Output
------
One JSON record per image, written incrementally so a partial run still yields
usable data. Every raw reply is retained alongside the parsed one; nothing is
post-processed into an invented score, because "score: 0" outside a 1-10 range is
a real answer from this model and rounding it into something sensible would be
fabricating data.

Usage:
    sprite_preview/run.sh moon_eval.py --images dirA dirB --out results.json
    sprite_preview/run.sh moon_eval.py --images dirA --repeat 3   # determinism
"""

import argparse
import base64
import io
import json
import os
import sys
import time
import urllib.request

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow missing; use sprite_preview/run.sh")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

OLLAMA = os.environ.get("OLLAMA_URL", "http://127.0.0.1:11434")
MODEL = os.environ.get("MOONDREAM_MODEL", "moondream:latest")

# Moondream resizes internally, but a 32px sprite gives it almost nothing to look
# at; nearest-neighbour upscale is what the probes used, so these answers
# correspond to that presentation.
PRESENT_PX = 320

# The constraint. `object` is the identification, `quality` is the grade asked
# for. `matches_request` is deliberately separate: "what is this" and "is it the
# thing that was requested" are different questions, and the model answers them
# differently (it called one sprite both "fireplace" and "bottle" depending on
# the prompt), so collapsing them would hide that.
SCHEMA = {
    "type": "object",
    "properties": {
        "object": {"type": "string"},
        # Named exactly as the question asks it. An earlier version called this
        # "matches_request" and the model answered "no" on all 8 images while
        # simultaneously reporting object="fireplace" -- a contradiction caused
        # by the field name, not the image. With the field named for the question
        # it answers "yes" correctly. Field naming is part of the prompt.
        "is_fireplace": {"type": "string", "enum": ["yes", "no", "partially"]},
        "quality": {"type": "string",
                    "enum": ["poor", "fair", "good", "excellent"]},
        "score": {"type": "integer", "minimum": 1, "maximum": 10},
    },
    "required": ["object", "is_fireplace", "quality", "score"],
}

PROMPT = ("What object is in this image? Is it a fireplace? Rate its visual "
          "quality and give it a score out of ten.")


def ask(blob, prompt=PROMPT, timeout=300, retries=3):
    """One constrained VQA call. Returns (parsed, raw_text, meta)."""
    last = None
    for _attempt in range(retries):
        try:
            payload = {
                "model": MODEL,
                "prompt": prompt,
                "images": [base64.b64encode(blob).decode()],
                "stream": False,
                # Grammar-constrained decoding: the reply cannot deviate from the
                # schema, which is what removes the free-form junk.
                "format": SCHEMA,
                "options": {"temperature": 0, "num_predict": 128},
            }
            req = urllib.request.Request(
                OLLAMA + "/api/generate",
                data=json.dumps(payload).encode(),
                headers={"Content-Type": "application/json"},
            )
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                body = json.loads(resp.read().decode())
            text = body.get("response", "")
            try:
                parsed = json.loads(text)
            except json.JSONDecodeError:
                parsed = None
            return parsed, text, {"done_reason": body.get("done_reason"),
                                  "eval_count": body.get("eval_count")}
        except Exception as exc:  # noqa: BLE001
            last = exc
            time.sleep(2)
    return None, f"[ERROR after {retries} attempts: {last}]", {}


def prepare(path, px=PRESENT_PX):
    """Flatten onto the game backdrop and upscale NEAREST, then PNG-encode.

    Compositing first matters: moondream has no notion of alpha, and a raw RGBA
    PNG shows as black wherever it is transparent, which changes what it reports.
    """
    with Image.open(path) as raw:
        img = raw.convert("RGBA")
        flat = Image.new("RGB", img.size, (24, 20, 28))
        flat.paste(img, (0, 0), img)
        flat = flat.resize((px, px), Image.NEAREST)
    buf = io.BytesIO()
    flat.save(buf, format="PNG")
    return buf.getvalue()


def collect(dirs):
    found = []
    for directory in dirs:
        if not os.path.isdir(directory):
            sys.exit(f"no such directory: {directory}")
        for name in sorted(os.listdir(directory)):
            if not name.endswith(".png"):
                continue
            if name.endswith("_sheet.png") or name.startswith("_"):
                continue
            found.append(os.path.join(directory, name))
    return found


def main():
    global MODEL

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--images", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--model", default=MODEL)
    ap.add_argument("--repeat", type=int, default=1,
                    help="ask each image N times to expose non-determinism")
    ap.add_argument("--prompt", default=PROMPT)
    args = ap.parse_args()
    MODEL = args.model

    paths = collect(args.images)
    if not paths:
        sys.exit("no images found")

    print(f"model: {MODEL}  endpoint: {OLLAMA}  constrained: json_schema")
    print(f"images: {len(paths)}  repeats: {args.repeat}")
    print()

    results = {"model": MODEL, "endpoint": OLLAMA, "schema": SCHEMA,
               "prompt": args.prompt, "items": []}

    for path in paths:
        rel = os.path.relpath(path, ROOT)
        print(f"--- {rel}")
        try:
            blob = prepare(path)
        except Exception as exc:
            print(f"    prepare failed: {exc}")
            results["items"].append({"file": rel, "error": str(exc)})
            continue

        entry = {"file": rel, "runs": []}
        for _index in range(args.repeat):
            parsed, text, meta = ask(blob, args.prompt)
            entry["runs"].append({"parsed": parsed, "raw": text, "meta": meta})
            if parsed:
                print(f"    object={parsed.get('object')!r:24s} "
                      f"is_fireplace={parsed.get('is_fireplace')!r:12s} "
                      f"quality={parsed.get('quality')!r:12s} "
                      f"score={parsed.get('score')}")
            else:
                print(f"    UNPARSED: {text[:120]!r}")
            with open(args.out, "w") as handle:
                json.dump(results, handle, indent=2)
        results["items"].append(entry)
        with open(args.out, "w") as handle:
            json.dump(results, handle, indent=2)
        print()

    with open(args.out, "w") as handle:
        json.dump(results, handle, indent=2)
    print(f"wrote {os.path.relpath(args.out, ROOT)}")


if __name__ == "__main__":
    main()
